/** 与课本单元数一致：按学期题库顺序均分到 Unit 1–6 */
const TEXTBOOK_UNIT_COUNT = 6;

function buildIdToUnitMap(ids: readonly string[]): Record<string, number> {
  const map: Record<string, number> = {};
  if (ids.length === 0) return map;
  const chunk = Math.max(1, Math.ceil(ids.length / TEXTBOOK_UNIT_COUNT));
  ids.forEach((id, i) => {
    map[id] = Math.min(TEXTBOOK_UNIT_COUNT, Math.floor(i / chunk) + 1);
  });
  return map;
}

